const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('companion', Object.freeze({
  state: () => ipcRenderer.invoke('companion:state'),
  info: () => ipcRenderer.invoke('companion:info'),
  update: patch => ipcRenderer.invoke('companion:update', patch),
  choosePet: () => ipcRenderer.invoke('companion:choose-pet'),
  resetPet: () => ipcRenderer.invoke('companion:reset-pet'),
  resetQuotes: () => ipcRenderer.invoke('companion:reset-quotes'),
  autoApp: () => ipcRenderer.invoke('companion:auto-app'),
  chooseApp: () => ipcRenderer.invoke('companion:choose-app'),
  resetPosition: () => ipcRenderer.invoke('companion:reset-position'),
  usage: () => ipcRenderer.invoke('companion:usage'),
  greeting: () => ipcRenderer.invoke('companion:greeting'),
  activity: () => ipcRenderer.send('companion:activity'),
  bubbleAction: action => ipcRenderer.invoke('companion:bubble-action', action),
  bubbleSize: size => ipcRenderer.invoke('companion:bubble-size', size),
  projectHome: () => ipcRenderer.invoke('companion:project-home'),
  settings: () => ipcRenderer.send('companion:settings'),
  menu: () => ipcRenderer.send('companion:menu'),
  dragStart: point => ipcRenderer.send('companion:drag-start', point),
  dragEnd: (cancel, point) => ipcRenderer.send('companion:drag-end', { cancel: cancel === true, point }),
  passThrough: value => ipcRenderer.send('companion:pass-through', value === true),
  open: () => ipcRenderer.invoke('companion:open'),
  onState: callback => { const listener = (_, state) => callback(state); ipcRenderer.on('companion:changed', listener); return () => ipcRenderer.removeListener('companion:changed', listener); },
  onAction: callback => { const listener = (_, action) => callback(action); ipcRenderer.on('companion:action', listener); return () => ipcRenderer.removeListener('companion:action', listener); },
  onBubble: callback => { const listener = (_, data) => callback(data); ipcRenderer.on('companion:bubble', listener); return () => ipcRenderer.removeListener('companion:bubble', listener); },
  onStatus: callback => { const listener = (_, status) => callback(status); ipcRenderer.on('companion:status', listener); return () => ipcRenderer.removeListener('companion:status', listener); },
}));
